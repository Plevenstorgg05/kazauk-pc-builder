"""Compare protected subsystem hashes with a baseline outside the checkout.

Usage: python3 scripts/verify-configurator-protection.py /tmp/ionz-protected-baseline.json
The baseline is captured before implementation, never generated by this check.
"""
import hashlib
import json
import pathlib
import sys

baseline = json.loads(pathlib.Path(sys.argv[1]).read_text())
changed = [name for name, digest in baseline.items()
           if not pathlib.Path(name).is_file()
           or hashlib.sha256(pathlib.Path(name).read_bytes()).hexdigest() != digest]
if changed:
    print("Protected files changed:", *changed, sep="\n")
    sys.exit(1)
print(f"All {len(baseline)} protected files are unchanged.")
